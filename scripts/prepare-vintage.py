"""Fetches the 1920s public-domain recordings listed in scripts/vintage-jazz.json
and prepares them for the Ambient screen:

  python3 scripts/prepare-vintage.py            # download (once) + process
  python3 scripts/prepare-vintage.py --offline  # process what's already downloaded

Downloads go to dist/vintage-raw/ (ignored by git). Each record is decoded,
trimmed, filtered for 78-rpm hiss and rumble, levelled to match the other
tracks, and encoded as mono AAC into app/music/vintage/. Writes
app/music/vintage.js, which adds them to the playlist as the '1920s' set.
Needs numpy, scipy and macOS's afconvert/afinfo.
"""
import argparse
import json
import math
import os
import shutil
import subprocess
import tempfile
import time
import urllib.error
import urllib.request
from pathlib import Path

import numpy as np
from scipy.io import wavfile
from scipy.signal import butter, sosfiltfilt

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "scripts" / "vintage-jazz.json"
RAW = ROOT / "dist" / "vintage-raw"
OUT = ROOT / "app" / "music" / "vintage"
SR = 44100
TARGET_RMS_DB = -21.0  # a touch under the originals (-19): mono 78s read louder
USER_AGENT = "CleanHubPersonal/0.1 (personal TV launcher)"


def download(track):
    RAW.mkdir(parents=True, exist_ok=True)
    dest = RAW / (track["id"] + ".mp3")
    if dest.exists() and dest.stat().st_size > 100_000:
        return dest
    req = urllib.request.Request(track["url"], headers={"User-Agent": USER_AGENT})
    tmp = dest.with_suffix(".part")
    # Wikimedia rate-limits bursts (HTTP 429): wait as asked, then retry.
    for attempt in range(6):
        try:
            with urllib.request.urlopen(req, timeout=60) as r, open(tmp, "wb") as f:
                kind = r.headers.get("Content-Type", "")
                if not kind.startswith("audio/"):
                    raise SystemExit(f"{track['id']}: expected audio, got {kind!r} from {track['url']}")
                shutil.copyfileobj(r, f, 1 << 16)
            break
        except urllib.error.HTTPError as e:
            if e.code != 429 or attempt == 5:
                raise
            wait = int(e.headers.get("Retry-After") or 0) or 10 * (attempt + 1)
            print(f"  {track['id']}: rate-limited, retrying in {wait}s")
            time.sleep(wait)
    tmp.rename(dest)
    time.sleep(3)  # be gentle between files
    return dest


def decode(src, tmp):
    wav = Path(tmp) / "decoded.wav"
    subprocess.run(["afconvert", "-f", "WAVE", "-d", f"LEI16@{SR}", "-c", "1", str(src), str(wav)],
                   check=True, capture_output=True)
    rate, x = wavfile.read(wav)
    assert rate == SR, rate
    return x.astype(np.float32) / 32768


def clean(x):
    """78-rpm transfers: rumble below 60 Hz and hiss above ~7 kHz carry no
    music. Trim near-silent lead-in/out, level, soft-limit, short fades."""
    sos = butter(2, [60, 7000], btype="band", fs=SR, output="sos")
    x = sosfiltfilt(sos, x).astype(np.float32)
    win = SR // 10
    frames = np.sqrt(np.mean(x[: len(x) // win * win].reshape(-1, win) ** 2, axis=1))
    loud = np.nonzero(frames > frames.max() * 0.03)[0]
    start, end = max(0, loud[0] - 2) * win, min(len(x), (loud[-1] + 3) * win)
    x = x[start:end]
    # Level by the loud passages (ignore the quiet tail of the distribution).
    frames = np.sqrt(np.mean(x[: len(x) // win * win].reshape(-1, win) ** 2, axis=1))
    level = np.sqrt(np.mean(np.sort(frames)[len(frames) // 4:] ** 2))
    x = x * (10 ** (TARGET_RMS_DB / 20) / max(level, 1e-9))
    x = np.tanh(x * 1.1) / 1.1
    fade_in, fade_out = int(0.3 * SR), int(1.5 * SR)
    x[:fade_in] *= np.linspace(0, 1, fade_in, dtype=np.float32)
    x[-fade_out:] *= np.linspace(1, 0, fade_out, dtype=np.float32)
    peak = float(np.abs(x).max())
    if peak > 0.89:
        x *= 0.89 / peak
    return x


def encode(x, name, tmp):
    wav = Path(tmp) / "clean.wav"
    wavfile.write(wav, SR, (x * 32767).astype(np.int16))
    enc = Path(tmp) / name
    subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", "96000", "-s", "0", str(wav), str(enc)],
                   check=True, capture_output=True)
    subprocess.run(["afinfo", str(enc)], check=True, capture_output=True)
    OUT.mkdir(parents=True, exist_ok=True)
    os.replace(enc, OUT / name)  # same volume (dist/ is in the repo), so atomic


def write_playlist(entries):
    lines = [
        "// Generated by scripts/prepare-vintage.py: 1920s U.S. public-domain recordings,",
        "// added to the Ambient playlist as the '1920s' set (sources in scripts/vintage-jazz.json).",
        "(function (root) {",
        "  'use strict';",
        "  const CH = root.CleanHub = root.CleanHub || {};",
        "  CH.playlist = (CH.playlist || []).concat(" + json.dumps(entries, indent=2).replace("\n", "\n  ") + ");",
        "})(typeof window !== 'undefined' ? window : globalThis);",
        "",
    ]
    (ROOT / "app" / "music" / "vintage.js").write_text("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", action="store_true", help="don't download; use dist/vintage-raw")
    args = ap.parse_args()
    if not shutil.which("afconvert"):
        raise SystemExit("afconvert (macOS) is needed; nothing was changed.")
    tracks = json.loads(SOURCES.read_text())["tracks"]
    (ROOT / "dist").mkdir(exist_ok=True)
    entries = []
    for n, t in enumerate(tracks, 1):
        src = RAW / (t["id"] + ".mp3") if args.offline else download(t)
        if not src.exists():
            raise SystemExit(f"missing {src}; run without --offline")
        name = f"{n:02d}-{t['id']}.m4a"
        with tempfile.TemporaryDirectory(dir=ROOT / "dist") as tmp:
            x = clean(decode(src, tmp))
            encode(x, name, tmp)
        size = (OUT / name).stat().st_size
        print(f"{name}: {len(x) / SR:5.0f}s, {size // 1024:5d} KB  ({src.stat().st_size // 1024} KB source)")
        entries.append({"file": "vintage/" + name, "title": t["title"], "artist": t["artist"], "year": t["year"],
                        "set": "1920s", "credit": "U.S. public domain recording. Source: " + t["page"]})
    write_playlist(entries)
    total = sum((OUT / f"{n:02d}-{t['id']}.m4a").stat().st_size for n, t in enumerate(tracks, 1))
    print(f"wrote app/music/vintage.js ({len(entries)} tracks, {total / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
