// Copies the bundled OFL fonts (latin subset) from @fontsource into app/fonts
// and writes app/css/fonts.css. The TV app must not fetch anything online.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const FONTS = [
  { pkg: 'manrope', family: 'Manrope', weights: [400, 600, 700] },
  { pkg: 'fraunces', family: 'Fraunces', weights: [400, 600, 700] },
  { pkg: 'space-grotesk', family: 'Space Grotesk', weights: [400, 600, 700] }
];

mkdirSync(ROOT + 'app/fonts', { recursive: true });
let css = '/* Generated by scripts/vendor-fonts.mjs. Fonts are SIL OFL 1.1; see fonts/*-LICENSE.txt. */\n';
for (const f of FONTS) {
  const dir = `${ROOT}node_modules/@fontsource/${f.pkg}/`;
  for (const w of f.weights) {
    const file = `${f.pkg}-latin-${w}-normal.woff2`;
    copyFileSync(dir + 'files/' + file, ROOT + 'app/fonts/' + file);
    css += `@font-face { font-family: '${f.family}'; font-style: normal; font-weight: ${w}; font-display: block; src: url(../fonts/${file}) format('woff2'); }\n`;
  }
  writeFileSync(`${ROOT}app/fonts/${f.pkg}-LICENSE.txt`, readFileSync(dir + 'LICENSE'));
}
writeFileSync(ROOT + 'app/css/fonts.css', css);
console.log('Fonts copied to app/fonts and app/css/fonts.css written.');
